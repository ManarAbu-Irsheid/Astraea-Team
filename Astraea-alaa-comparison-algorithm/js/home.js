/**
 * Orbital planet carousel.
 * The three planets sit on one tilted elliptical orbit around the globe.
 * The active planet is the 3D globe at the front; the other two wait on the
 * back of the orbit, smaller and blurred. Switching rotates them along the
 * ellipse. Under 760px the original row of thumbnails is kept.
 */
function initOrbitCarousel() {
  const stage = document.querySelector('.planet-3d-stage');
  const group = document.querySelector('.planet-tabs-group');
  const backSvg = document.getElementById('orbitRingBack');
  const frontSvg = document.getElementById('orbitRingFront');
  const P3D = window.Planetary3D;
  if (!stage || !group || !backSvg || !frontSvg || !P3D) return;

  const order = (P3D.planetsList && P3D.planetsList.length) ? P3D.planetsList : ['earth', 'mars', 'moon'];
  const buttons = {};
  group.querySelectorAll('.planet-tab-btn').forEach(b => { buttons[b.getAttribute('data-planet')] = b; });

  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
  const mobileQuery = window.matchMedia('(max-width: 760px)');
  const SLOT = { front: 90, right: 330, left: 210 }; // degrees on the ellipse (y grows downward)
  const angles = {};
  let geo = null;
  let animId = null;

  const slotsFor = (active) => {
    const i = order.indexOf(active);
    const n = order.length;
    return {
      [order[i]]: SLOT.front,
      [order[(i + 1) % n]]: SLOT.right,
      [order[(i - 1 + n) % n]]: SLOT.left
    };
  };

  const measure = () => {
    const w = stage.clientWidth;
    const h = stage.clientHeight;
    const globeD = h * 0.9;                        // camera fov 45°, distance 2.8 -> globe ≈ 0.9 of stage height
    const rx = Math.max(w * 0.38, globeD * 0.62);
    const ry = rx * 0.28;
    const thumb = Math.round(Math.min(130, Math.max(56, globeD * 0.22)));
    geo = { w, h, cx: w / 2, cy: h / 2, rx, ry, thumb };

    const d = (from, to) => {
      // ellipse arc between two angles (deg), sampled
      const pts = [];
      for (let a = from; a <= to; a += 2) {
        const r = a * Math.PI / 180;
        pts.push(`${(geo.cx + rx * Math.cos(r)).toFixed(1)},${(geo.cy + ry * Math.sin(r)).toFixed(1)}`);
      }
      return 'M' + pts.join(' L');
    };
    [backSvg, frontSvg].forEach(svg => {
      svg.setAttribute('viewBox', `0 0 ${w} ${h}`);
      svg.setAttribute('width', w);
      svg.setAttribute('height', h);
    });
    backSvg.querySelector('path').setAttribute('d', d(180, 360));
    frontSvg.querySelector('path').setAttribute('d', d(0, 180));
  };

  const place = (planet, deg) => {
    const btn = buttons[planet];
    if (!btn || !geo) return;
    const r = deg * Math.PI / 180;
    const x = geo.cx + geo.rx * Math.cos(r);
    const y = geo.cy + geo.ry * Math.sin(r);
    const depth = Math.sin(r);                      // -1 back … +1 front
    const frontness = Math.max(0, depth);
    const scale = 1 + frontness * 1.2;
    btn.style.setProperty('--orbit-size', geo.thumb + 'px');
    btn.style.left = x + 'px';
    btn.style.top = y + 'px';
    btn.style.transform = `translate(-50%, -50%) scale(${scale.toFixed(3)})`;
    btn.style.opacity = (0.8 * (1 - Math.min(1, frontness * 1.6))).toFixed(3);
    // While passing behind the globe the planet must sit under the 3D canvas;
    // everywhere else it stays above it so it can be clicked.
    const behindGlobe = depth < 0 && Math.abs(x - geo.cx) < geo.h * 0.5;
    btn.style.zIndex = behindGlobe ? '1' : '3';
    btn.style.pointerEvents = depth > 0.5 ? 'none' : 'auto';
    btn.tabIndex = depth > 0.5 ? -1 : 0;
  };

  const applyAll = () => order.forEach(p => place(p, angles[p]));

  const shortest = (from, to) => {
    let diff = ((to - from) % 360 + 540) % 360 - 180;
    return from + diff;
  };

  const animateTo = (active) => {
    const targets = slotsFor(active);
    if (animId) cancelAnimationFrame(animId);
    if (reduceMotion.matches || !geo) {
      order.forEach(p => { angles[p] = targets[p]; });
      applyAll();
      return;
    }
    const start = {};
    const end = {};
    order.forEach(p => { start[p] = angles[p]; end[p] = shortest(angles[p], targets[p]); });
    const t0 = performance.now();
    const dur = 900;
    const ease = t => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
    const step = (now) => {
      const k = ease(Math.min(1, (now - t0) / dur));
      order.forEach(p => { angles[p] = start[p] + (end[p] - start[p]) * k; });
      applyAll();
      if (k < 1) animId = requestAnimationFrame(step);
      else order.forEach(p => { angles[p] = ((targets[p] % 360) + 360) % 360; });
    };
    animId = requestAnimationFrame(step);
  };

  const enable = () => {
    const on = !mobileQuery.matches;
    stage.classList.toggle('orbit-mode', on);
    if (!on) {
      Object.values(buttons).forEach(b => {
        ['left', 'top', 'transform', 'opacity', 'zIndex', 'pointerEvents'].forEach(k => { b.style[k] = ''; });
        b.tabIndex = 0;
      });
      return;
    }
    measure();
    const targets = slotsFor(P3D.currentPlanet || order[0]);
    order.forEach(p => { if (angles[p] === undefined) angles[p] = targets[p]; });
    applyAll();
  };

  // Rotate the orbit whenever the active planet changes (tabs, arrows, anything)
  const origSwitch = P3D.switchPlanet.bind(P3D);
  P3D.switchPlanet = function (p) {
    const changed = p !== P3D.currentPlanet;
    origSwitch(p);
    if (changed && stage.classList.contains('orbit-mode')) animateTo(p);
  };

  let resizeTimer = null;
  window.addEventListener('resize', () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(enable, 120);
  });
  if (mobileQuery.addEventListener) mobileQuery.addEventListener('change', enable);

  enable();
}


/**
 * Occasional shooting stars across the fixed space background.
 * One at a time, every 5–11 s, only while the tab is visible.
 */
function initShootingStars() {
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const sky = document.querySelector('.space-living-background');
  if (!sky) return;

  const launch = () => {
    if (!document.hidden) {
      const star = document.createElement('span');
      star.className = 'shooting-star';
      star.style.left = (10 + Math.random() * 80) + '%';
      star.style.top = (3 + Math.random() * 40) + '%';
      star.style.setProperty('--angle', (140 + Math.random() * 30) + 'deg');
      star.style.setProperty('--distance', (320 + Math.random() * 260) + 'px');
      star.addEventListener('animationend', () => star.remove());
      sky.appendChild(star);
    }
    setTimeout(launch, 5000 + Math.random() * 6000);
  };
  setTimeout(launch, 2500);
}
